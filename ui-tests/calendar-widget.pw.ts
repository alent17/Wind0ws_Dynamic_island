import { test, expect } from "@playwright/test";

test("seven-day calendar expands into a selectable month with day differences", async ({page}) => {
  await page.clock.setFixedTime(new Date("2026-10-27T12:00:00Z"));
  await page.goto("/ui-tests/island-fixture.html");
  await page.evaluate(() => (window as any).configureIsland({mode:"expanded",offset:225,scale:.65}));
  await page.locator(".island-surface").focus();
  await page.keyboard.press("F2");
  await page.locator(".catalog-item").filter({has:page.locator(".app-icon.calendar")}).click();
  await expect(page.locator('[data-widget-kind="calendar"]')).toBeVisible();
  await page.locator(".edit-actions .done").click();
  const calendar = page.locator(".calendar-widget");
  await expect(calendar.locator(".date-cell strong")).toHaveText(["25","26","27","28","29","30","31"]);
  await expect(calendar.locator(".expand-hint")).toHaveCount(0);
  await expect(calendar.locator('[aria-current="date"] strong')).toHaveText("27");
  const original = await page.locator(".island-surface").boundingBox();
  await calendar.hover(); await page.mouse.wheel(0,120);
  const extension = page.locator(".calendar-extension");
  await expect(extension).toBeVisible();
  await expect(extension.locator(".day")).toHaveCount(31);
  const grid = await extension.locator(".month-grid").boundingBox();
  const lastDay = await extension.locator(".day").last().boundingBox();
  expect(lastDay!.y + lastDay!.height).toBeLessThanOrEqual(grid!.y + grid!.height + 1);
  await expect(extension.locator('.day[aria-current="date"]')).toHaveText("27");
  await extension.locator(".day").filter({hasText:/^29$/}).click();
  await expect(extension.locator(".date-detail strong")).toContainText("2");
  const futureLabel = await extension.locator(".date-detail strong").innerText();
  await expect(extension.locator(".day.selected")).toHaveText("29");
  await expect(extension.locator('.day[aria-current="date"]')).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await expect(extension.locator(".day.selected")).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await extension.locator(".day").filter({hasText:/^25$/}).click();
  await expect(extension.locator(".date-detail strong")).toContainText("2");
  await expect(extension.locator(".date-detail strong")).not.toHaveText(futureLabel);
  const yearSelect = extension.locator('[data-picker-trigger="year"]'), monthSelect = extension.locator('[data-picker-trigger="month"]');
  const monthBefore = await monthSelect.innerText();
  await expect(yearSelect).toContainText("2026");
  await extension.locator(".month-actions button").last().click();
  await expect(monthSelect).not.toHaveText(monthBefore);
  await extension.locator(".day").filter({hasText:/^1$/}).click();
  await expect(extension.locator(".date-detail strong")).toContainText("5");
  await extension.locator(".today-button").click();
  await expect(monthSelect).toHaveText(monthBefore);
  await expect(extension.locator(".day.selected")).toHaveText("27");
  await yearSelect.click();
  await expect(yearSelect).toHaveAttribute("aria-expanded", "true");
  await expect(extension.locator('.picker-menu [data-year="2026"]')).toHaveAttribute("aria-selected", "true");
  const yearMenu = extension.locator(".picker-menu");
  const beforeScroll = await yearMenu.evaluate(node => node.scrollTop);
  await yearMenu.hover(); await page.mouse.wheel(0,120);
  await expect.poll(() => yearMenu.evaluate(node => node.scrollTop)).toBeGreaterThan(beforeScroll);
  await extension.locator('.picker-menu [data-year="2024"]').click();
  await expect(yearSelect).toContainText("2024");
  await expect(yearSelect).toHaveAttribute("aria-expanded", "false");
  await monthSelect.click();
  await extension.locator('.picker-menu [data-month="1"]').click();
  await expect(extension.locator(".day")).toHaveCount(29);
  await extension.locator(".day").filter({hasText:/^29$/}).click();
  await expect(extension.locator(".day.selected")).toHaveText("29");
  await extension.locator(".today-button").click();
  await expect(yearSelect).toContainText("2026");
  await expect(monthSelect).toHaveText(monthBefore);
  await yearSelect.focus(); await page.keyboard.press("ArrowDown");
  await expect(yearSelect).toHaveAttribute("aria-expanded", "true");
  await page.keyboard.press("Escape");
  await expect(yearSelect).toHaveAttribute("aria-expanded", "false");
  await expect(extension).toBeVisible();
  await monthSelect.click();
  const backdrop = await extension.locator(".picker-backdrop").boundingBox();
  await page.mouse.click(backdrop!.x + backdrop!.width / 2, backdrop!.y + backdrop!.height - 24);
  await expect(monthSelect).toHaveAttribute("aria-expanded", "false");
  await expect(extension).toBeVisible();
  await expect(extension.locator('.day[aria-current="date"]')).toHaveCSS("background-color", "rgb(25, 58, 142)");
  const expanded = await page.locator(".island-surface").boundingBox();
  expect(expanded!.height).toBeGreaterThan(original!.height);
  await extension.locator("header button").first().click();
  await expect(extension).toHaveCount(0);
  await expect(calendar.locator(".date-cell strong")).toHaveText(["25","26","27","28","29","30","31"]);
});

test("expanding the calendar does not change system volume", async ({page}) => {
  await page.goto("/ui-tests/lifecycle-fixture.html");
  await page.waitForFunction(() => (window as any).ready);
  await page.evaluate(() => {
    const f = window as any;
    f.settingsOverrides = {islandStyle:"edge",islandEdge:"top",enableAnimations:false,wheelVolumeControl:true,islandWidgets:{left:[],right:["calendar"]},islandWidgetsEnabled:true};
    f.mountApp();
  });
  await expect(page.locator(".fixed-host")).toBeVisible();
  await page.evaluate(() => (window as any).expand());
  const calendar = page.locator(".calendar-widget");
  await expect(calendar).toBeVisible();
  const before = await page.evaluate(() => (window as any).volumeWrites.length);
  await calendar.hover(); await page.mouse.wheel(0,120);
  await expect(page.locator(".calendar-extension")).toBeVisible();
  expect(await page.evaluate(() => (window as any).volumeWrites.length)).toBe(before);
  const yearTrigger = page.locator('[data-picker-trigger="year"]');
  await yearTrigger.click();
  await page.locator(".picker-menu").hover(); await page.mouse.wheel(0,120);
  expect(await page.evaluate(() => (window as any).volumeWrites.length)).toBe(before);
  await page.keyboard.press("Escape");
  await expect(yearTrigger).toHaveAttribute("aria-expanded", "false");
  await expect(page.locator(".calendar-extension")).toBeVisible();
  await page.locator(".calendar-extension header button").first().click();
  await expect(page.locator(".calendar-extension")).toHaveCount(0);
  await expect(calendar).toBeVisible();
  await page.evaluate(() => (window as any).destroy());
});

test("desktop styles keep today blue when another date is selected or today is hovered", async ({page}) => {
  await page.clock.setFixedTime(new Date("2026-10-27T12:00:00Z"));
  await page.goto("/ui-tests/lifecycle-fixture.html");
  await page.waitForFunction(() => (window as any).ready);
  await page.evaluate(() => {
    const f = window as any;
    f.settingsOverrides = {islandStyle:"edge",islandEdge:"top",enableAnimations:false,clockTimeZone:"Asia/Shanghai",islandWidgets:{left:["volume"],right:["calendar"]},islandWidgetsEnabled:true};
    f.mountApp();
  });
  await expect(page.locator(".fixed-host")).toBeVisible();
  await page.evaluate(() => (window as any).expand());
  const card = page.locator(".calendar-widget");
  await expect(card).toBeVisible();
  await card.hover(); await page.mouse.wheel(0,120);
  const extension = page.locator(".calendar-extension");
  const today = extension.locator('.day[aria-current="date"]');
  await expect(today).toHaveText("27");
  await expect(today).toHaveCSS("background-color", "rgb(25, 58, 142)");
  const other = extension.locator(".day").filter({hasText:/^29$/});
  await other.click();
  await expect(other).toHaveAttribute("aria-pressed", "true");
  await expect(today).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await expect(other).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await today.hover();
  await expect(today).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await today.focus();
  await expect(today).toHaveCSS("background-color", "rgb(25, 58, 142)");
  await page.evaluate(() => (window as any).destroy());
});

