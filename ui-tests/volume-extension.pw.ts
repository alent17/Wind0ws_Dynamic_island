  await expect(panel).toBeVisible();
  await panel.locator(".device-trigger").click();
  await panel.locator(".device-menu").hover();
  const writesBefore = await page.evaluate(() => (window as any).volumeWrites.length);
  await page.mouse.wheel(0, 120);
  await page.waitForTimeout(150);
  await expect(page.locator(".app-mixer")).toHaveCount(0);
  expect(await page.evaluate(() => (window as any).volumeWrites.length)).toBe(writesBefore);
  await panel.locator(".device-trigger").click();
