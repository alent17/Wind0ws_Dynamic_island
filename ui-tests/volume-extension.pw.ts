test("app volume pages show at most five sessions and clamp when apps disappear", async ({page}) => {
  await page.goto("/ui-tests/lifecycle-fixture.html");
  await page.waitForFunction(() => (window as any).ready);
  await page.evaluate(() => {
    const f = window as any;
    f.settingsOverrides = {islandStyle:"floating",islandEdge:"top",enableAnimations:false,islandWidgets:{left:[],right:["volume"]},islandWidgetsEnabled:true};
    f.mixerSessions = Array.from({length:11}, (_, i) => ({processId:i+1,deviceId:"fixture-device",name:`App ${i+1}`,icon:null,volumePercent:50,muted:false,systemSounds:false}));
    f.mixerWrites = [];
    const invoke = f.__TAURI_INTERNALS__.invoke;
    f.__TAURI_INTERNALS__.invoke = (command:string,args:any,options:any) => {
      if (command === "list_app_audio_sessions") return Promise.resolve(f.mixerSessions.map((session:any) => ({...session})));
      if (command === "set_app_audio_volume") { f.mixerWrites.push(args); return Promise.resolve(); }
      return invoke(command,args,options);
    };
    f.mountApp();
  });
  await expect(page.locator(".fixed-host")).toBeVisible();
  await page.evaluate(() => (window as any).expand());
  const panel = page.locator('[data-widget-kind="volume"] .panel-volume');
  await expect(panel).toBeVisible();
  await panel.hover(); await page.mouse.wheel(0,120);
  const rows = page.locator(".app-row"), pagination = page.locator(".pagination");
  await expect(rows).toHaveCount(5);
  await expect(pagination.locator("span")).toHaveText("1 / 3");
  const fullPageHeight = (await page.locator(".island-surface").boundingBox())!.height;
  expect(await page.locator(".app-list").evaluate(node => node.scrollHeight <= node.clientHeight + 1)).toBe(true);
  const previous = pagination.locator("button").first(), next = pagination.locator("button").last();
  await expect(previous).toBeDisabled();
  await next.click();
  await expect(pagination.locator("span")).toHaveText("2 / 3");
  await expect(rows).toHaveCount(5);
  await expect(rows.first()).toHaveAttribute("title", "App 6");
  await rows.first().locator('input[type="range"]').fill("68");
  await expect.poll(() => page.evaluate(() => (window as any).mixerWrites.at(-1))).toMatchObject({processId:6,volumePercent:68});
  await next.click();
  await expect(pagination.locator("span")).toHaveText("3 / 3");
  await expect(rows).toHaveCount(1);
  await expect(next).toBeDisabled();
  await expect.poll(async () => (await page.locator(".island-surface").boundingBox())!.height).toBeLessThan(fullPageHeight - 50);
  const lastRow = await rows.last().boundingBox(), pager = await pagination.boundingBox(), island = await page.locator(".island-surface").boundingBox();
  expect(lastRow!.y + lastRow!.height).toBeLessThanOrEqual(pager!.y + 1);
  expect(pager!.y + pager!.height).toBeLessThanOrEqual(island!.y + island!.height + 1);
  await page.evaluate(() => (window as any).mixerSessions.length = 6);
  await page.locator(".app-mixer .refresh").click();
  await expect(pagination.locator("span")).toHaveText("2 / 2");
  await expect(rows).toHaveCount(1);
  await previous.click();
  await expect(rows).toHaveCount(5);
  await page.evaluate(() => (window as any).mixerSessions.length = 2);
  await page.locator(".app-mixer .refresh").click();
  await expect(rows).toHaveCount(2);
  await expect(pagination).toHaveCount(0);
  await page.evaluate(() => (window as any).destroy());
});

for (const kind of ["calendar", "volume", "clock"]) test(`desktop ${kind} keeps the preview animation when the native viewport is one pixel smaller`, async ({page}) => {
  await page.goto("/ui-tests/lifecycle-fixture.html");
  await page.waitForFunction(() => (window as any).ready);
  await page.evaluate(kind => {
    const f = window as any;
    f.settingsOverrides = {islandStyle:"edge",islandEdge:"top",enableAnimations:true,reduceAnimations:false,islandWidgets:{left:[],right:[kind]},islandWidgetsEnabled:true};
    const invoke = f.__TAURI_INTERNALS__.invoke;
    f.__TAURI_INTERNALS__.invoke = (command:string,args:any,options:any) => command === "list_app_audio_sessions"
      ? Promise.resolve(Array.from({length:4},(_,i)=>({processId:i+1,deviceId:"fixture-device",name:`App ${i+1}`,icon:null,volumePercent:50,muted:false,systemSounds:false})))
      : invoke(command,args,options);
    f.mountApp();
  }, kind);
  const host = page.locator(".fixed-host");
  await expect(host).toBeVisible();
  await page.evaluate(() => (window as any).expand());
  const panel = page.locator(kind === "calendar" ? ".calendar-widget" : kind === "clock" ? '[data-widget-kind="clock"] .info-panel' : '[data-widget-kind="volume"] .panel-volume');
  await expect(panel).toBeVisible();
  await page.waitForTimeout(800);
  const bounds = await host.boundingBox();
  await page.setViewportSize({width:Math.floor(bounds!.width)-1,height:Math.floor(bounds!.height)-1});
  await page.waitForTimeout(200);
  await panel.hover();
  const capture = () => page.evaluate(async () => {
    const widths:number[] = [];
    for(let i=0;i<45;i++) {
      await new Promise(requestAnimationFrame);
      widths.push(document.querySelector(".island-surface")!.getBoundingClientRect().width);
    }
    return widths;
  });
  const frames = capture();
  await page.mouse.wheel(0,120);
  const widths = await frames;
  expect(new Set(widths.map(width => Math.round(width))).size).toBeGreaterThan(6);
  const extension = page.locator(kind === "calendar" ? ".calendar-extension" : kind === "clock" ? ".world-clock-extension" : ".app-mixer");
  await expect(extension).toBeVisible();
  const closing = capture();
  await extension.locator("header button").first().click();
  expect(new Set((await closing).map(width => Math.round(width))).size).toBeGreaterThan(6);
  await expect(extension).toHaveCount(0);
  await page.evaluate(() => (window as any).destroy());
});
