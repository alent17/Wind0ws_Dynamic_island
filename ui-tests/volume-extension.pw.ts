  await expect.poll(() => page.evaluate(() => (window as any).mixerWrites.at(-1))).toMatchObject({volumePercent:null,muted:false});
  await expect(page.locator(".app-row .app-value").first()).toHaveText("75");
  await page.evaluate(() => (window as any).deferMute = true);
  await icon.click();
