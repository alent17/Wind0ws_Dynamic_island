  await expect.poll(() => page.evaluate(() => (window as any).mixerWrites.at(-1))).toMatchObject({volumePercent:null,muted:true});
  await expect(page.locator(".app-row .app-value").first()).toHaveText("0");
  await page.locator(".app-mixer .refresh").click();
  await expect(icon).toHaveAttribute("aria-pressed", "true");
  await icon.click();
