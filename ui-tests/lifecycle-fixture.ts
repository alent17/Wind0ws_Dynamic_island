import { mount, unmount, tick } from "svelte";
import { mockIPC, mockWindows } from "@tauri-apps/api/mocks";
import { DEFAULT_SETTINGS } from "../src/lib/api/types";
import { settingsStore } from "../src/lib/settingsStore";
import { emit } from "@tauri-apps/api/event";
import { transitionIsland } from "../src/lib/islandStore";
import App from "../src/App.svelte";
import RollingFixture from "./RollingFixture.svelte";
import "../src/app.css";
const fixture = window as any;
fixture.calls = [];
fixture.animations = [];
const animate = Element.prototype.animate;
Element.prototype.animate = function(...args) {
  const animation = animate.apply(this, args);
  const row = {firstOpacity:(args[0] as Keyframe[])[0].opacity,cancelled:0};
  fixture.animations.push(row);
  const cancel = animation.cancel.bind(animation);
  animation.cancel = () => { row.cancelled++; cancel(); };
  return animation;
};
mockWindows("main");
mockIPC((command, args) => {
  fixture.calls.push(command);
  if (command === "get_settings") return {...DEFAULT_SETTINGS,showSpectrum:false,idleContentEnabled:false};
  if (command === "get_monitors") return [{width:1920,height:1080,x:0,y:0,workX:0,workY:0,workWidth:1920,workHeight:1080,scaleFactor:1}];
  if (command === "plugin:window|available_monitors") return [{name:"test",position:{x:0,y:0},size:{width:1920,height:1080},scaleFactor:1}];
  if (command === "get_idle_snapshot") return {weatherUpdatedAt:null,weatherForecast:[]};
  if (command === "get_media_info_cmd") return {title:"",artist:"",source:"",isPlaying:false};
  if (command === "list_media_sessions") return [];
  if (command === "request_artwork") return null;
}, {shouldMockEvents:true});
let app: ReturnType<typeof mount>;
fixture.mountApp = () => { app = mount(App,{target:document.getElementById("app")!}); };
fixture.mountDigit = () => { app = mount(RollingFixture,{target:document.getElementById("app")!}); };
fixture.destroy = async () => { await unmount(app); await tick(); };
fixture.changeEdge = () => settingsStore.update(settings => ({...settings,islandEdge:"left"}));
fixture.expand = () => transitionIsland({type:"expand"});
fixture.media = (payload: unknown) => emit("media-update",payload);
fixture.ready = true;
