import { describe, expect, it } from "vitest";
import { DEFAULT_SETTINGS, normalizeAppSettings } from "./types";

describe("normalizeAppSettings", () => {
  it("defaults notification access off and preserves an explicit choice", () => {
    expect(normalizeAppSettings({}).notificationsEnabled).toBe(false);
    expect(normalizeAppSettings({ notificationsEnabled: true }).notificationsEnabled).toBe(true);
  });
  it("defaults to CDP but preserves an explicit standard connection", () => {
    expect(normalizeAppSettings({}).neteaseConnectionMode).toBe("enhanced");
    expect(normalizeAppSettings({ neteaseAutoConnect: true }).neteaseConnectionMode).toBe("enhanced");
    expect(normalizeAppSettings({ neteaseExecutablePath: "C:\\Music\\cloudmusic.exe" }).neteaseConnectionMode).toBe("enhanced");
    expect(normalizeAppSettings({ neteaseConnectionMode: "standard", neteaseAutoConnect: true }).neteaseConnectionMode).toBe("standard");
    expect(normalizeAppSettings({ neteaseAutoConnect: false, playerSourceOverrides: { player: "netease" } }).neteaseConnectionMode).toBe("enhanced");
  });
  it("defaults and independently normalizes expanded lengths", () => {
    expect(normalizeAppSettings({}).floatingExpandedLength).toBe(600);
    expect(normalizeAppSettings({}).edgeExpandedLength).toBe(600);
    const settings = normalizeAppSettings({ floatingExpandedLength: 750, edgeExpandedLength: 520 });
    expect(settings.floatingExpandedLength).toBe(750);
    expect(settings.edgeExpandedLength).toBe(520);
    expect(normalizeAppSettings({ floatingExpandedLength: NaN }).floatingExpandedLength).toBe(600);
    expect(normalizeAppSettings({ edgeExpandedLength: 2000 }).edgeExpandedLength).toBe(900);
  });

  it("keeps session identity choices scoped to exact IDs and migrates old settings", () => {
    expect(normalizeAppSettings({}).playerSourceOverrides).toEqual({});
    expect(normalizeAppSettings({playerSourceOverrides:{"Microsoft.AutoGenerated.test":"netease","":"netease",other:"invalid"}}).playerSourceOverrides)
      .toEqual({"Microsoft.AutoGenerated.test":"netease"});
  });
  it("keeps the old real progress behavior when a persisted setting is missing", () => {
    expect(normalizeAppSettings({}).neteaseProgressMode).toBe("real");
  });

  it("preserves estimate and safely defaults an invalid runtime value", () => {
    expect(normalizeAppSettings({ neteaseProgressMode: "estimate" }).neteaseProgressMode).toBe("estimate");
    expect(normalizeAppSettings({ neteaseProgressMode: "unknown" as never }).neteaseProgressMode)
      .toBe(DEFAULT_SETTINGS.neteaseProgressMode);
  });

  it("prefers explicit mode values and seeds missing values from legacy shared settings", () => {
    const legacy = normalizeAppSettings({
      compactLength: 164,
      expandedCornerRadius: 62,
      floatingCompactLength: 220,
      floatingExpandedCornerRadius: 70,
    } as never);
    expect(legacy.floatingCompactLength).toBe(220);
    expect(legacy.edgeCompactLength).toBe(164);
    expect(legacy.floatingExpandedCornerRadius).toBe(70);
    expect(legacy.edgeExpandedCornerRadius).toBe(62);
  });
});
